# shellcheck shell=bash
# povy's link with mise. A conf.d file of mise's global config includes the
# profile's team.toml, so its tools, [env] and aliases apply in every directory.
# mise bootstrap then applies the profile's mise.toml, with the secrets of .env in
# its environment.

# The oldest mise that has what povy relies on, such as bootstrap status --json.
POVY_MISE_MIN="2026.11.0"
POVY_SECRET_RE='^[A-Za-z_][A-Za-z0-9_]*$'

# Succeeds when the mise found here is at least POVY_MISE_MIN.
mise_recent_enough() {
  local version
  version=$(mise_run --version 2>/dev/null | awk '{ print $1; exit }') || return 1
  [ -n "$version" ] || return 1
  [ "$(printf '%s\n%s\n' "$POVY_MISE_MIN" "$version" | sort -t. -k1,1n -k2,2n -k3,3n | head -n 1)" = "$POVY_MISE_MIN" ]
}

mise_require_recent() {
  mise_recent_enough ||
    die "povy needs mise $POVY_MISE_MIN or later; update it with your package manager, or with: mise self-update"
}

# The conf.d file of the current context. A context's only includes its team.toml:
# the default one, in mise's global config, also has the tool povy reads with.
team_conf_render() {
  if [ -n "$CONTEXT_ID" ]; then
    printf '%s\n' "$POVY_CONTEXT_HEADER"
    # shellcheck disable=SC2153 # Set with CONTEXT_ID by context_select.
    printf '# The team.toml of context %s, in every directory below %s.\n' "$CONTEXT_ID" "$(tilde_path "$CONTEXT_DIR")"
    printf 'include = ["%s"]\n' "$(toml_escape "$PROFILE_TEAM")"
    return 0
  fi
  echo '# Generated by povy apply. Changes here are overwritten.'
  if [ -n "$PROFILE_TEAM" ]; then
    echo "# The profile's team.toml, in every directory."
    printf 'include = ["%s"]\n' "$(toml_escape "$PROFILE_TEAM")"
  fi
  echo '# povy reads its own configuration with yq.'
  echo '[tools]'
  printf '"%s" = "%s"\n' "${POVY_YQ_TOOL%@*}" "${POVY_YQ_TOOL#*@}"
}

team_conf_write() {
  local tmp
  tmp=$(mktemp "$POVY_STATE_DIR/mise-conf.XXXXXX") || die "cannot write in $POVY_STATE_DIR"
  team_conf_render >"$tmp"
  install_file "$tmp" "${CONTEXT_CONF:-$POVY_MISE_CONF}" 644
  rm -f "$tmp"
}

# mise only applies a project it trusts. The profile is the one the user chose.
team_trust() {
  [ -n "$PROFILE_PROJECT" ] || return 0
  mise_run trust --quiet "$PROFILE_PROJECT" >/dev/null || die "mise could not trust $PROFILE_PROJECT; see above"
}

# Prints the environment variables of the secrets that the profile's files read,
# the only ones that mise bootstrap status lists.
team_secret_names() {
  local status names name
  [ -n "$PROFILE_PROJECT" ] || return 0
  status=$(mise_run bootstrap status --json -C "$POVY_PROFILE_ROOT") ||
    die "mise cannot read the profile; see above"
  names=$(printf '%s\n' "$status" | "$POVY_YQ" -p json '(.secrets // [])[].env') ||
    die "unexpected output from mise bootstrap status"
  while IFS= read -r name; do
    [ -n "$name" ] && [ "$name" != null ] || continue
    [[ "$name" =~ $POVY_SECRET_RE ]] || die "the profile reads an invalid secret name: $name"
    printf '%s\n' "$name"
  done <<<"$names"
}

# Prints the secrets that neither .env nor the environment provides.
team_secrets_missing() {
  local names=$1 name value
  while IFS= read -r name; do
    [ -n "$name" ] || continue
    value=$(env_value "$name") || value=""
    [ -n "$value" ] || [ -n "${!name:-}" ] || printf '%s\n' "$name"
  done <<<"$names"
}

# Runs mise with the secrets of .env exported to it, and never passed as arguments.
# It keeps the terminal, for the sudo prompts of mise bootstrap.
team_mise_with_secrets() {
  local names=$1 bin
  shift
  bin=$(mise_find) || die "mise is not installed; run the povy bootstrap first"
  (
    while IFS= read -r name; do
      [ -n "$name" ] || continue
      value=$(env_value "$name") || continue
      [ -z "$value" ] || export "$name=$value"
    done <<<"$names"
    cd "$HOME" && MISE_YES=1 "$bin" "$@"
  )
}

# mise bootstrap replaces a file that differs from the profile's without keeping a
# copy. povy keeps one, as for the files it writes itself, with the content of a
# link's target, as mise may write through the link.
team_backup_files() {
  local status targets target
  status=$(team_mise_with_secrets "$1" bootstrap status --json -C "$POVY_PROFILE_ROOT") ||
    die "mise cannot read the profile; see above"
  targets=$(printf '%s\n' "$status" |
    "$POVY_YQ" -p json '(.files // [])[] | select(.id.kind == "file" and .action == "update") | .id.name') ||
    die "unexpected output from mise bootstrap status"
  while IFS= read -r target; do
    [ -f "$target" ] || continue
    backup_file "$target" follow-link
  done <<<"$targets"
}

team_bootstrap() {
  team_mise_with_secrets "$1" bootstrap --yes -C "$POVY_PROFILE_ROOT" >&2 ||
    die "mise bootstrap failed on the profile; see above"
}

# Without a mise.toml, there is nothing to bootstrap, but the team's tools still
# need installing. Those of a context apply only below its directory, where mise
# installs them from.
team_install_tools() {
  mise_run ${CONTEXT_DIR:+-C "$CONTEXT_DIR"} install >&2 ||
    die "mise could not install the tools${CONTEXT_ID:+ of context $CONTEXT_ID}"
}
