# shellcheck shell=bash
# bivy apply: idempotent. Nothing is written until the configuration, the secrets
# and every template have been checked.

BIVY_STAGING=""

apply_cleanup() {
  [ -z "$BIVY_STAGING" ] || rm -rf "$BIVY_STAGING"
}

# Rendered files hold secrets, so the staging directory is private and removed on
# every exit. Template failures stop here, before the home directory changes.
apply_render_files() {
  local source target index=0
  BIVY_STAGING=$(mktemp -d "$BIVY_STATE_DIR/staging.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  trap apply_cleanup EXIT
  while IFS=$'\t' read -r source target; do
    [ -n "$source" ] || continue
    index=$((index + 1))
    (umask 077 && template_render "$BIVY_PROFILE_DIR/$source" "$BIVY_STAGING/$index") ||
      die "could not render $source"
  done <<<"$PROFILE_FILES"
}

apply_install_files() {
  local source target index=0
  while IFS=$'\t' read -r source target; do
    [ -n "$source" ] || continue
    index=$((index + 1))
    install_file "$BIVY_STAGING/$index" "$HOME/$target" 600
  done <<<"$PROFILE_FILES"
}

# Writes the merged tools as a mise config of their own, then installs them.
apply_tools() {
  local merged name versions version level tmp list
  local -a specs=()
  merged=$(tools_merged)
  tmp=$(mktemp "$BIVY_STATE_DIR/tools.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  {
    echo '# Generated by bivy apply. Changes here are overwritten.'
    echo '[tools]'
    while IFS=$'\t' read -r name versions level; do
      case "$versions" in
        *' '*)
          list=""
          for version in $versions; do
            list="$list${list:+, }\"$version\""
          done
          printf '"%s" = [%s]\n' "$name" "$list"
          ;;
        *) printf '"%s" = "%s"\n' "$name" "$versions" ;;
      esac
    done <<<"$merged"
  } >"$tmp"
  install_file "$tmp" "$BIVY_MISE_CONF" 644
  rm -f "$tmp"

  while IFS=$'\t' read -r name versions level; do
    for version in $versions; do
      specs[${#specs[@]}]="$name@$version"
    done
  done <<<"$merged"
  info "installing tools with mise: ${specs[*]}"
  mise_run install "${specs[@]}" >&2 || die "mise could not install the tools"
  mise_run reshim >&2 || die "mise could not refresh its shims"
}

# What bivy banner checks in each new terminal, so that it does not read the
# profile again. Rewritten on every apply: its date is the date of the last one.
apply_write_status() {
  local tmp secret source target
  tmp=$(mktemp "$BIVY_STATE_DIR/applied.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  {
    echo '# Written by bivy apply for bivy banner.'
    printf 'profile\t%s\n' "$CFG_PROFILE"
    while IFS= read -r secret; do
      [ -z "$secret" ] || printf 'secret\t%s\n' "$secret"
    done <<<"$PROFILE_SECRETS"
    while IFS=$'\t' read -r source target; do
      [ -z "$source" ] || printf 'file\t%s\n' "$target"
    done <<<"$PROFILE_FILES"
  } >"$tmp"
  mv -f "$tmp" "$BIVY_APPLIED" || die "cannot write $BIVY_APPLIED"
}

cmd_apply() {
  local missing
  [ $# -eq 0 ] || die "apply takes no argument"

  bivy_init_paths
  bivy_load_os
  os_preflight
  bivy_ensure_dirs
  yq_ensure
  config_load
  env_ensure
  profile_sync "$CFG_PROFILE"
  profile_load "$CFG_PROFILE"
  env_seed "$PROFILE_SECRETS"

  missing=$(env_missing "$PROFILE_SECRETS")
  if [ -n "$missing" ]; then
    info "$missing"
    die "the secrets above are empty; fill them in $BIVY_ENV_FILE"
  fi

  apply_render_files
  apply_tools
  shell_write_env
  shell_write_interactive
  shell_apply_blocks
  gui_apply
  git_apply
  apply_install_files

  case "${SHELL:-}" in
    */fish) warn "fish is not supported yet; add $BIVY_SHIMS_DIR to its PATH yourself" ;;
  esac
  apply_write_status
  info "Applied: $BIVY_WRITTEN written, $BIVY_UNCHANGED unchanged, $BIVY_BACKED_UP backed up."
  if [ "$BIVY_BACKED_UP" -gt 0 ]; then
    info "Backups are in $BIVY_BACKUP_DIR"
  fi
}
