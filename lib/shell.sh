# shellcheck shell=bash
# Puts the mise shims on PATH for every shell through a marked block in the
# startup files, which sources a single generated env.sh.
#
# Shims rather than `mise activate`: they behave the same with or without an
# interactive prompt, which is what IDEs and agents need.

BIVY_BLOCK_START='# >>> bivy >>>'
BIVY_BLOCK_END='# <<< bivy <<<'

# Writes a path as shell source, using $HOME when possible so that the block
# stays valid in a dotfiles repository shared between machines.
shell_path_literal() {
  local path=$1 rest
  case "$path" in
    "$HOME"/*)
      rest=${path#"$HOME"/}
      if [[ "$rest" =~ ^[A-Za-z0-9._/-]+$ ]]; then
        # shellcheck disable=SC2016
        printf '"$HOME/%s"' "$rest"
        return 0
      fi
      ;;
  esac
  printf "'%s'" "$(printf '%s' "$path" | sed "s/'/'\\\\''/g")"
}

# POSIX on purpose: .profile may be read by dash. Dirs are moved to the front
# rather than skipped when present, because path_helper on macOS and /etc/profile
# on some distributions reorder PATH between .zshenv and the login files.
shell_write_env() {
  local tmp
  tmp=$(mktemp "$BIVY_STATE_DIR/env.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  {
    cat <<'EOF'
# Generated by bivy apply. Changes here are overwritten.
__bivy_path_front() {
  case ":$PATH:" in
    ":$1:"*) return 0 ;;
    *":$1:"*)
      __bivy_p=":$PATH:"
      __bivy_p="${__bivy_p%%:"$1":*}:${__bivy_p#*:"$1":}"
      __bivy_p="${__bivy_p#:}"
      PATH="${__bivy_p%:}"
      ;;
  esac
  PATH="$1${PATH:+:$PATH}"
}
EOF
    printf '__bivy_path_front %s\n' "$(shell_path_literal "$BIVY_LOCAL_BIN")"
    printf '__bivy_path_front %s\n' "$(shell_path_literal "$BIVY_SHIMS_DIR")"
    echo 'export PATH'
    echo 'unset -f __bivy_path_front'
    echo 'unset __bivy_p'
  } >"$tmp"
  install_file "$tmp" "$BIVY_ENV_SH" 644
  rm -f "$tmp"
}

shell_block() {
  local env_path
  env_path=$(shell_path_literal "$BIVY_ENV_SH")
  printf '%s\n' "$BIVY_BLOCK_START"
  echo '# Managed by bivy. Edits inside this block are overwritten.'
  printf 'if [ -r %s ]; then . %s; fi\n' "$env_path" "$env_path"
  printf '%s\n' "$BIVY_BLOCK_END"
}

# Inserts the block at the top of the file, above the "return if not interactive"
# guard of a stock .bashrc, or refreshes it in place. Content outside the block is
# not touched, and a symlinked dotfile stays a symlink.
shell_block_apply() {
  local file=$1 block starts ends current tmp
  block=$(shell_block)
  tmp=$(mktemp "$BIVY_STATE_DIR/block.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"

  if [ ! -e "$file" ]; then
    printf '%s\n' "$block" >"$file" || die "cannot write $file"
    rm -f "$tmp"
    BIVY_WRITTEN=$((BIVY_WRITTEN + 1))
    info "wrote $file"
    return 0
  fi

  starts=$(grep -cxF "$BIVY_BLOCK_START" "$file") || starts=0
  ends=$(grep -cxF "$BIVY_BLOCK_END" "$file") || ends=0

  if [ "$starts" -eq 0 ] && [ "$ends" -eq 0 ]; then
    { printf '%s\n' "$block" && cat "$file"; } >"$tmp"
  elif [ "$starts" -eq 1 ] && [ "$ends" -eq 1 ]; then
    current=$(awk -v s="$BIVY_BLOCK_START" -v e="$BIVY_BLOCK_END" '
      $0 == s { on = 1 }
      on { print }
      $0 == e { on = 0 }
    ' "$file")
    if [ "$current" = "$block" ]; then
      rm -f "$tmp"
      BIVY_UNCHANGED=$((BIVY_UNCHANGED + 1))
      return 0
    fi
    BIVY_BLOCK_TEXT="$block" awk -v s="$BIVY_BLOCK_START" -v e="$BIVY_BLOCK_END" '
      $0 == s { on = 1; print ENVIRON["BIVY_BLOCK_TEXT"]; next }
      $0 == e { on = 0; next }
      !on { print }
    ' "$file" >"$tmp"
  else
    rm -f "$tmp"
    die "$file has an incomplete bivy block; remove its markers and run bivy apply again"
  fi

  backup_file "$file" follow-link
  cat "$tmp" >"$file" || die "cannot write $file"
  rm -f "$tmp"
  BIVY_WRITTEN=$((BIVY_WRITTEN + 1))
  info "updated $file"
}

# Bash reads only the first of these it finds at login, so creating another one
# would hide the file already in use.
shell_bash_login_file() {
  local name
  for name in .bash_profile .bash_login .profile; do
    if [ -e "$HOME/$name" ]; then
      printf '%s\n' "$HOME/$name"
      return 0
    fi
  done
  printf '%s\n' "$HOME/$(os_bash_login_default)"
}

# .zshenv covers every zsh, the login files come after path_helper, .bashrc covers
# interactive bash and commands run over SSH.
shell_startup_files() {
  local zdir=${ZDOTDIR:-$HOME}
  if command -v zsh >/dev/null 2>&1 || [ -e "$zdir/.zshenv" ]; then
    printf '%s\n' "$zdir/.zshenv" "$zdir/.zprofile"
  fi
  if command -v bash >/dev/null 2>&1; then
    printf '%s\n' "$HOME/.bashrc"
    shell_bash_login_file
  fi
}

shell_apply_blocks() {
  local file files
  files=$(shell_startup_files)
  while IFS= read -r file; do
    [ -n "$file" ] || continue
    shell_block_apply "$file"
  done <<<"$files"
}
