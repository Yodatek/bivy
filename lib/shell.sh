# shellcheck shell=bash
# Puts the mise shims on PATH for every shell through a marked block in the
# startup files, which sources a single generated env.sh.
#
# Shims rather than `mise activate`: they behave the same with or without an
# interactive prompt, which is what IDEs and agents need.

# Writes a path as shell source, using $HOME when possible so that the block
# stays valid in a dotfiles repository shared between machines.
shell_path_literal() {
  local path=$1 rest
  case "$path" in
    "$HOME"/*)
      rest=${path#"$HOME"/}
      if [[ "$rest" =~ ^[A-Za-z0-9._/-]+$ ]]; then
        # shellcheck disable=SC2016
        printf '"$HOME/%s"' "$rest"
        return 0
      fi
      ;;
  esac
  printf "'%s'" "$(printf '%s' "$path" | sed "s/'/'\\\\''/g")"
}

# POSIX on purpose: .profile may be read by dash. Dirs are moved to the front
# rather than skipped when present, because path_helper on macOS and /etc/profile
# on some distributions reorder PATH between .zshenv and the login files.
shell_write_env() {
  local tmp
  tmp=$(mktemp "$BIVY_STATE_DIR/env.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  {
    cat <<'EOF'
# Generated by bivy apply. Changes here are overwritten.
__bivy_path_front() {
  case ":$PATH:" in
    ":$1:"*) return 0 ;;
    *":$1:"*)
      __bivy_p=":$PATH:"
      __bivy_p="${__bivy_p%%:"$1":*}:${__bivy_p#*:"$1":}"
      __bivy_p="${__bivy_p#:}"
      PATH="${__bivy_p%:}"
      ;;
  esac
  PATH="$1${PATH:+:$PATH}"
}
EOF
    printf '__bivy_path_front %s\n' "$(shell_path_literal "$BIVY_LOCAL_BIN")"
    printf '__bivy_path_front %s\n' "$(shell_path_literal "$BIVY_SHIMS_DIR")"
    echo 'export PATH'
    echo 'unset -f __bivy_path_front'
    echo 'unset __bivy_p'
  } >"$tmp"
  install_file "$tmp" "$BIVY_ENV_SH" 644
  rm -f "$tmp"
}

# Interactive shells only: shows the banner once per shell, in a terminal. The
# guard on the variable covers a .bash_profile that sources .bashrc.
# The installed starship binary rather than its shim, which adds a mise run, about
# 45 ms, to every prompt drawn. starship init writes into the prompt the starship
# that PATH finds, so it runs with a PATH that does not hold the shims, and prints
# its full code at once: bash would otherwise run a second step with the user's PATH.
prompt_starship_path() {
  mise_run which starship 2>/dev/null
}

# Interactive shells only. The banner shows once per shell, in a terminal; the
# guards on the variables cover a .bash_profile that sources .bashrc. The prompt
# also shows in IDE terminals, but not in a dumb one.
shell_write_interactive() {
  local tmp prompt starship=""
  prompt=$(prompt_choice)
  if [ "$prompt" = starship ]; then
    starship=$(prompt_starship_path) || starship=""
    [ -n "$starship" ] || warn "starship is not installed; the prompt stays as it is"
  fi
  tmp=$(mktemp "$BIVY_STATE_DIR/interactive.XXXXXX") || die "cannot write in $BIVY_STATE_DIR"
  # shellcheck disable=SC2016 # Shell code written for the startup files.
  {
    echo '# Generated by bivy apply. Changes here are overwritten.'
    if [ "$CFG_BANNER" = false ] && [ -z "$starship" ]; then
      echo '# Nothing to do: banner = false and no prompt in config.toml or the profile.'
    else
      echo 'case $- in *i*) ;; *) return 0 ;; esac'
    fi
    if [ "$CFG_BANNER" != false ]; then
      echo 'if [ -t 1 ] && [ -z "${__bivy_banner_shown:-}" ]; then'
      echo '  __bivy_banner_shown=1'
      printf '  %s banner --auto\n' "$(shell_path_literal "$BIVY_ROOT/bin/bivy")"
      echo 'fi'
    fi
    if [ -n "$starship" ]; then
      starship=$(shell_path_literal "$starship")
      printf 'if [ -z "${__bivy_prompt_set:-}" ] && [ "${TERM:-}" != dumb ] && [ -x %s ]; then\n' "$starship"
      echo '  __bivy_prompt_set=1'
      echo '  if [ -n "${ZSH_VERSION:-}" ]; then'
      printf '    eval "$(PATH=/usr/bin:/bin %s init zsh --print-full-init)"\n' "$starship"
      echo '  elif [ -n "${BASH_VERSION:-}" ]; then'
      printf '    eval "$(PATH=/usr/bin:/bin %s init bash --print-full-init)"\n' "$starship"
      echo '  fi'
      echo 'fi'
    fi
  } >"$tmp"
  install_file "$tmp" "$BIVY_INTERACTIVE_SH" 644
  rm -f "$tmp"
}

# The block of each startup file sources env.sh, interactive.sh or both.
shell_block() {
  local parts=$1 name=${2:-} part path
  printf '%s\n' "$(block_start "$name")"
  echo '# Managed by bivy. Edits inside this block are overwritten.'
  for part in $parts; do
    case "$part" in
      env) path=$(shell_path_literal "$BIVY_ENV_SH") ;;
      interactive) path=$(shell_path_literal "$BIVY_INTERACTIVE_SH") ;;
    esac
    printf 'if [ -r %s ]; then . %s; fi\n' "$path" "$path"
  done
  printf '%s\n' "$(block_end "$name")"
}

# Usage: shell_block_apply FILE [PARTS] [top|bottom] [NAME]
shell_block_apply() {
  block_apply "$1" "$(shell_block "${2:-env}" "${4:-}")" "${3:-top}" "${4:-}"
}

# Bash reads only the first of these it finds at login, so creating another one
# would hide the file already in use.
shell_bash_login_file() {
  local name
  for name in .bash_profile .bash_login .profile; do
    if [ -e "$HOME/$name" ]; then
      printf '%s\n' "$HOME/$name"
      return 0
    fi
  done
  printf '%s\n' "$HOME/$(os_bash_login_default)"
}

# Prints "file<TAB>parts<TAB>position<TAB>name" for each block. env goes at the top
# of .zshenv and .bashrc, above the "return if not interactive" guard of a stock
# .bashrc, and at the bottom of the login files, which run after path_helper and
# often prepend to PATH themselves, as brew shellenv does. interactive goes at the
# bottom of the files that interactive shells read, after a framework such as Oh My
# Zsh or a .bashrc that sets the prompt. .bashrc holds both, so the second block is
# named.
shell_startup_files() {
  local zdir=${ZDOTDIR:-$HOME}
  if command -v zsh >/dev/null 2>&1 || [ -e "$zdir/.zshenv" ]; then
    printf '%s\tenv\ttop\t\n' "$zdir/.zshenv"
    printf '%s\tenv\tbottom\t\n' "$zdir/.zprofile"
    printf '%s\tinteractive\tbottom\t\n' "$zdir/.zshrc"
  fi
  if command -v bash >/dev/null 2>&1; then
    printf '%s\tenv\ttop\t\n' "$HOME/.bashrc"
    printf '%s\tinteractive\tbottom\tinteractive\n' "$HOME/.bashrc"
    printf '%s\tenv interactive\tbottom\t\n' "$(shell_bash_login_file)"
  fi
}

shell_apply_blocks() {
  local file files parts position name
  files=$(shell_startup_files)
  while IFS=$'\t' read -r file parts position name; do
    [ -n "$file" ] || continue
    shell_block_apply "$file" "$parts" "$position" "$name"
  done <<<"$files"
}

# Prints the commands of the tools that mise has active from HOME. Only their shims
# work everywhere: the shim of a tool set for one project fails elsewhere, so
# another copy coming first in PATH is no problem.
mise_active_commands() {
  local dir file
  mise_run bin-paths 2>/dev/null | while IFS= read -r dir; do
    for file in "$dir"/*; do
      if [ -f "$file" ] && [ -x "$file" ]; then
        printf '%s\n' "${file##*/}"
      fi
    done
  done | sort -u
}

# Prints "command<TAB>dir" for each command given, one per line, whose mise shim a
# directory placed before the shims in the given PATH hides. Plain bash with no
# process started, as the banner runs it in every new terminal. Nothing when the
# shims are not on that PATH at all.
shims_shadowed() {
  local search=$1 commands=$2 name dir
  local -a dirs
  case ":$search:" in
    *":$BIVY_SHIMS_DIR:"*) ;;
    *) return 0 ;;
  esac
  IFS=: read -r -a dirs <<<"$search"
  while IFS= read -r name; do
    [ -n "$name" ] && [ -x "$BIVY_SHIMS_DIR/$name" ] || continue
    for dir in ${dirs[@]+"${dirs[@]}"}; do
      [ "$dir" != "$BIVY_SHIMS_DIR" ] || break
      if [ -n "$dir" ] && [ -f "$dir/$name" ] && [ -x "$dir/$name" ]; then
        printf '%s\t%s\n' "$name" "$dir"
        break
      fi
    done
  done <<<"$commands"
}

# One phrase per hiding directory: "/opt/homebrew/bin hides helm, sops".
shims_shadowed_summary() {
  printf '%s\n' "$1" | awk -F'\t' -v home="$HOME/" '
    NF == 2 {
      if (!($2 in tools)) order[++n] = $2
      tools[$2] = tools[$2] (tools[$2] == "" ? "" : ", ") $1
    }
    END {
      for (i = 1; i <= n; i++) {
        dir = order[i]
        if (index(dir, home) == 1) dir = "~/" substr(dir, length(home) + 1)
        printf "%s%s hides %s", (i > 1 ? "; " : ""), dir, tools[order[i]]
      }
    }'
}
