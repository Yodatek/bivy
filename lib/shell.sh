# shellcheck shell=bash
# Puts the mise shims and ~/.local/bin on PATH for every shell, through a marked
# block in the startup files that sources a single generated env.sh.
#
# This is what mise's own activation cannot do: its blocks run `mise`, which a
# shell started by an IDE from the Dock, or by an agent, does not have on its PATH.
# env.sh holds absolute paths, so the shims are there whatever PATH a shell starts
# with. The profiles' commands, their [_.povy] bin, come before ~/.local/bin, the
# first in config.toml first.

# Writes a path as shell source, using $HOME when possible so that the block
# stays valid in a dotfiles repository shared between machines.
shell_path_literal() {
  local path=$1 rest
  case "$path" in
    "$HOME"/*)
      rest=${path#"$HOME"/}
      if [[ "$rest" =~ ^[A-Za-z0-9._/-]+$ ]]; then
        # shellcheck disable=SC2016
        printf '"$HOME/%s"' "$rest"
        return 0
      fi
      ;;
  esac
  printf "'%s'" "$(printf '%s' "$path" | sed "s/'/'\\\\''/g")"
}

# POSIX on purpose: .profile may be read by dash. Dirs are moved to the front
# rather than skipped when present, because path_helper on macOS and /etc/profile
# on some distributions reorder PATH between .zshenv and the login files.
shell_write_env() {
  local tmp
  tmp=$(mktemp "$POVY_STATE_DIR/env.XXXXXX") || die "cannot write in $POVY_STATE_DIR"
  {
    cat <<'EOF'
# Generated by povy apply. Changes here are overwritten.
__povy_path_front() {
  case ":$PATH:" in
    ":$1:"*) return 0 ;;
    *":$1:"*)
      __povy_p=":$PATH:"
      __povy_p="${__povy_p%%:"$1":*}:${__povy_p#*:"$1":}"
      __povy_p="${__povy_p#:}"
      PATH="${__povy_p%:}"
      ;;
  esac
  PATH="$1${PATH:+:$PATH}"
}
EOF
    printf '__povy_path_front %s\n' "$(shell_path_literal "$POVY_LOCAL_BIN")"
    # Each moves to the front, so the last written ends up first.
    printf '%s\n' "${POVY_BINS:-}" | awk 'NF { line[++n] = $0 } END { for (i = n; i >= 1; i--) print line[i] }' |
      while IFS= read -r dir; do
        printf '__povy_path_front %s\n' "$(shell_path_literal "$dir")"
      done
    printf '__povy_path_front %s\n' "$(shell_path_literal "$POVY_SHIMS_DIR")"
    echo 'export PATH'
    echo 'unset -f __povy_path_front'
    echo 'unset __povy_p'
  } >"$tmp"
  install_file "$tmp" "$POVY_ENV_SH" 644
  rm -f "$tmp"
}

# Interactive shells only: the banner, once per shell, in a terminal. The guard on
# the variable covers a .bash_profile that sources .bashrc. Aliases, functions and
# the prompt belong to the profile, which mise bootstrap writes into the rc files.
shell_write_interactive() {
  local tmp
  tmp=$(mktemp "$POVY_STATE_DIR/interactive.XXXXXX") || die "cannot write in $POVY_STATE_DIR"
  # shellcheck disable=SC2016 # Shell code written for the startup files.
  {
    echo '# Generated by povy apply. Changes here are overwritten.'
    if [ "$CFG_BANNER" = false ]; then
      echo '# Nothing to do: banner = false.'
    else
      echo 'case $- in *i*) ;; *) return 0 ;; esac'
      echo 'if [ -t 1 ] && [ -z "${__povy_banner_shown:-}" ]; then'
      echo '  __povy_banner_shown=1'
      printf '  %s banner --auto\n' "$(shell_path_literal "$POVY_ROOT/bin/povy")"
      echo 'fi'
    fi
  } >"$tmp"
  install_file "$tmp" "$POVY_INTERACTIVE_SH" 644
  rm -f "$tmp"
}

# The block of each startup file sources env.sh, interactive.sh or both.
shell_block() {
  local parts=$1 name=${2:-} part path
  printf '%s\n' "$(block_start "$name")"
  echo '# Managed by povy. Edits inside this block are overwritten.'
  for part in $parts; do
    case "$part" in
      env) path=$(shell_path_literal "$POVY_ENV_SH") ;;
      interactive) path=$(shell_path_literal "$POVY_INTERACTIVE_SH") ;;
    esac
    printf 'if [ -r %s ]; then . %s; fi\n' "$path" "$path"
  done
  printf '%s\n' "$(block_end "$name")"
}

# Usage: shell_block_apply FILE [PARTS] [top|bottom] [NAME]
shell_block_apply() {
  block_apply "$1" "$(shell_block "${2:-env}" "${4:-}")" "${3:-top}" "${4:-}"
}

# Bash reads only the first of these it finds at login, so creating another one
# would hide the file already in use.
shell_bash_login_file() {
  local name
  for name in .bash_profile .bash_login .profile; do
    if [ -e "$HOME/$name" ]; then
      printf '%s\n' "$HOME/$name"
      return 0
    fi
  done
  printf '%s\n' "$HOME/$(os_bash_login_default)"
}

# Prints "file<TAB>parts<TAB>position<TAB>name" for each block. env goes at the top
# of .zshenv and .bashrc, above the "return if not interactive" guard of a stock
# .bashrc, and at the bottom of the login files, which run after path_helper and
# often prepend to PATH themselves, as brew shellenv does. interactive goes at the
# bottom of the files that interactive shells read, after a framework such as Oh My
# Zsh or a .bashrc that sets the prompt. .bashrc holds both, so the second block is
# named.
#
# zsh reads ~/.zshenv first, unless ZDOTDIR is already set when it starts: then it
# reads $ZDOTDIR/.zshenv instead. A ZDOTDIR set in ~/.zshenv itself only moves the
# later files. So env goes in ~/.zshenv always, and in $ZDOTDIR/.zshenv as well.
shell_startup_files() {
  local zdir=${ZDOTDIR:-$HOME}
  if command -v zsh >/dev/null 2>&1 || [ -e "$zdir/.zshenv" ] || [ -e "$HOME/.zshenv" ]; then
    printf '%s\tenv\ttop\t\n' "$HOME/.zshenv"
    if [ "$zdir" != "$HOME" ]; then
      printf '%s\tenv\ttop\t\n' "$zdir/.zshenv"
    fi
    printf '%s\tenv\tbottom\t\n' "$zdir/.zprofile"
    printf '%s\tinteractive\tbottom\t\n' "$zdir/.zshrc"
  fi
  if command -v bash >/dev/null 2>&1; then
    printf '%s\tenv\ttop\t\n' "$HOME/.bashrc"
    printf '%s\tinteractive\tbottom\tinteractive\n' "$HOME/.bashrc"
    printf '%s\tenv interactive\tbottom\t\n' "$(shell_bash_login_file)"
  fi
}

shell_apply_blocks() {
  local file files parts position name
  files=$(shell_startup_files)
  while IFS=$'\t' read -r file parts position name; do
    [ -n "$file" ] || continue
    shell_block_apply "$file" "$parts" "$position" "$name"
  done <<<"$files"
}

# Prints the commands of the tools that mise has active from HOME. Only their shims
# work everywhere: the shim of a tool set for one project fails elsewhere, so
# another copy coming first in PATH is no problem.
mise_active_commands() {
  local dir file
  mise_run bin-paths 2>/dev/null | while IFS= read -r dir; do
    for file in "$dir"/*; do
      if [ -f "$file" ] && [ -x "$file" ]; then
        printf '%s\n' "${file##*/}"
      fi
    done
  done | sort -u
}

# Prints "command<TAB>dir" for each command given, one per line, whose mise shim a
# directory placed before the shims in the given PATH hides. Nothing when the
# shims are not on that PATH at all. The install directories of mise do not count:
# `mise activate` puts them first on purpose, and they hold the same tools.
shims_shadowed() {
  local search=$1 commands=$2 name dir
  local -a dirs
  case ":$search:" in
    *":$POVY_SHIMS_DIR:"*) ;;
    *) return 0 ;;
  esac
  IFS=: read -r -a dirs <<<"$search"
  while IFS= read -r name; do
    [ -n "$name" ] && [ -x "$POVY_SHIMS_DIR/$name" ] || continue
    for dir in ${dirs[@]+"${dirs[@]}"}; do
      [ "$dir" != "$POVY_SHIMS_DIR" ] || break
      case "$dir/" in
        "$POVY_INSTALLS_DIR/"*) continue ;;
      esac
      if [ -n "$dir" ] && [ -f "$dir/$name" ] && [ -x "$dir/$name" ]; then
        printf '%s\t%s\n' "$name" "$dir"
        break
      fi
    done
  done <<<"$commands"
}

# One phrase per hiding directory: "/opt/homebrew/bin hides helm, sops".
shims_shadowed_summary() {
  printf '%s\n' "$1" | awk -F'\t' -v home="$HOME/" '
    NF == 2 {
      if (!($2 in tools)) order[++n] = $2
      tools[$2] = tools[$2] (tools[$2] == "" ? "" : ", ") $1
    }
    END {
      for (i = 1; i <= n; i++) {
        dir = order[i]
        if (index(dir, home) == 1) dir = "~/" substr(dir, length(home) + 1)
        printf "%s%s hides %s", (i > 1 ? "; " : ""), dir, tools[order[i]]
      }
    }'
}
