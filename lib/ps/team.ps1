# povy's link with mise, as in the bash engine: a conf.d file of mise's global
# config includes the profile's team.toml in every directory, then mise bootstrap
# applies the profile's mise.toml with the secrets of .env in its environment. On
# Windows, where mise writes no file, povy writes the files of [_.povy.windows].

# The oldest mise that has what povy relies on, such as bootstrap status --json.
$script:PovyMiseMin = [version]'2026.11.0'

function Test-PovyMiseRecent {
    $line = Invoke-PovyMise --version 2>$null | Select-Object -First 1
    $parsed = $null
    if (-not $line -or -not [version]::TryParse(([string]$line).Split(' ')[0], [ref]$parsed)) { return $false }
    return $parsed -ge $script:PovyMiseMin
}

function Assert-PovyMiseRecent {
    if (-not (Test-PovyMiseRecent)) {
        Stop-Povy "povy needs mise $($script:PovyMiseMin) or later; update it with winget, or with: mise self-update"
    }
}

# The conf.d file of the current context. A context's includes its team.toml and
# sets its variables, which mise lets win over the team.toml's: the default one, in
# mise's global config, also has the tool povy reads with.
function Get-PovyMiseConfText {
    $lines = [System.Collections.Generic.List[string]]::new()
    if ($script:Ctx -and $script:Ctx.Id) {
        $where = Format-PovyPath $script:Ctx.Dir
        $lines.Add($script:PovyContextHeader)
        if ($script:Prof.Team) {
            $lines.Add("# The team.toml of context $($script:Ctx.Id), in every directory below $where.")
            $lines.Add('include = [' + (ConvertTo-PovyTomlString $script:Prof.Team.Replace('\', '/')) + ']')
        }
        if ($script:Ctx.Env.Count -gt 0) {
            $lines.Add("# The env of context $($script:Ctx.Id) in config.toml, in every directory below $where.")
            $lines.Add('[env]')
            foreach ($name in $script:Ctx.Env.Keys) {
                # A literal ~/ of config.toml, which mise does not expand.
                $value = [string]$script:Ctx.Env[$name]
                if ($value -ceq '~') {
                    $value = $script:PovyHome
                } elseif ($value.StartsWith('~/')) {
                    $value = [System.IO.Path]::GetFullPath((Join-Path $script:PovyHome $value.Substring(2)))
                }
                $lines.Add("$name = " + (ConvertTo-PovyTomlString $value))
            }
        }
        return ($lines -join "`n") + "`n"
    }
    $lines.Add('# Generated by povy apply. Changes here are overwritten.')
    if ($script:Prof.Team) {
        $lines.Add("# The profile's team.toml, in every directory.")
        $lines.Add('include = [' + (ConvertTo-PovyTomlString $script:Prof.Team.Replace('\', '/')) + ']')
    }
    $lines.Add('# povy reads its own configuration with yq.')
    $lines.Add('[tools]')
    $yq = $script:PovyYqTool.Split('@')
    $lines.Add('"' + $yq[0] + '" = "' + $yq[1] + '"')
    return ($lines -join "`n") + "`n"
}

function Write-PovyMiseConf {
    $target = if ($script:PovyContextConf) { $script:PovyContextConf } else { $script:PovyMiseConf }
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
    $staged = New-PovyStagedFile (Get-PovyMiseConfText)
    try {
        Install-PovyFile $staged $target
    } finally {
        Remove-Item -LiteralPath $staged -Force -ErrorAction Ignore
    }
}

# mise only applies a project it trusts. The profile is the one the user chose.
function Set-PovyMiseTrust {
    if (-not $script:Prof.Project) { return }
    Invoke-PovyMise trust --quiet $script:Prof.Project 2>$null | Out-Null
    if ($LASTEXITCODE -ne 0) { Stop-Povy "mise could not trust $($script:Prof.Project)" }
}

# The environment variables that the profile's secrets read: those that mise reports,
# and those of the files povy writes on Windows, which mise leaves out there as their
# entries say os = "unix".
function Get-PovySecretName {
    if (-not $script:Prof.Project) { return @() }
    $json = Invoke-PovyMise bootstrap status --json -C $script:PovyProfileRoot 2>$null
    if ($LASTEXITCODE -ne 0) {
        Stop-Povy "mise cannot read the profile's mise.toml; run: mise bootstrap status -C $script:PovyProfileRoot"
    }
    $status = ($json -join "`n") | ConvertFrom-Json -AsHashtable
    $names = [System.Collections.Generic.List[string]]::new()
    foreach ($secret in @($status['secrets'])) {
        if ($secret -and $secret['env'] -cmatch $script:PovyEnvNameRe) { $names.Add($secret['env']) }
    }
    foreach ($file in $script:Prof.WindowsFiles) {
        if (-not $file.Template) { continue }
        foreach ($match in [System.Text.RegularExpressions.Regex]::Matches($file.Content, 'secret\(\s*name\s*=\s*(["''])([A-Za-z0-9._-]+)\1\s*\)')) {
            $name = $match.Groups[2].Value
            if ($script:Prof.Secrets.ContainsKey($name)) { $names.Add($script:Prof.Secrets[$name]) }
        }
    }
    return @($names | Select-Object -Unique)
}

# The secrets that neither .env nor the environment provides.
function Get-PovySecretMissing([string[]]$Names) {
    return @($Names | Where-Object { -not (Get-PovyEnvValue $_) -and -not [Environment]::GetEnvironmentVariable($_) })
}

# Runs mise with the secrets of .env in its environment, never as arguments.
function Invoke-PovyMiseWithSecret([string[]]$Names, [string[]]$Arguments) {
    $saved = @{}
    foreach ($name in $Names) {
        $value = Get-PovyEnvValue $name
        if (-not $value) { continue }
        $saved[$name] = [Environment]::GetEnvironmentVariable($name)
        [Environment]::SetEnvironmentVariable($name, $value)
    }
    try {
        Invoke-PovyMise @Arguments
    } finally {
        foreach ($name in $saved.Keys) { [Environment]::SetEnvironmentVariable($name, $saved[$name]) }
    }
}

function Invoke-PovyBootstrap([string[]]$Names) {
    if ($script:Prof.Project) {
        Invoke-PovyMiseWithSecret $Names @('bootstrap', '--yes', '-C', $script:PovyProfileRoot) |
            ForEach-Object { [Console]::Error.WriteLine($_) }
        if ($LASTEXITCODE -ne 0) { Stop-Povy 'mise bootstrap failed on the profile; see above' }
    } elseif (-not ($script:Ctx -and $script:Ctx.Id)) {
        Invoke-PovyMise install | ForEach-Object { [Console]::Error.WriteLine($_) }
        if ($LASTEXITCODE -ne 0) { Stop-Povy 'mise could not install the tools' }
    }
    # A context's team.toml applies only below its directory, where mise installs its
    # tools from.
    if ($script:Ctx -and $script:Ctx.Id -and $script:Prof.Team) {
        Invoke-PovyMise -C $script:Ctx.Dir install | ForEach-Object { [Console]::Error.WriteLine($_) }
        if ($LASTEXITCODE -ne 0) { Stop-Povy "mise could not install the tools of context $($script:Ctx.Id)" }
    }
}

# Renders the Windows files of the profile, in memory: a template that cannot be
# rendered stops apply before anything is written.
function Get-PovyWindowsFileContent {
    return @(foreach ($file in $script:Prof.WindowsFiles) {
            $text = if ($file.Template) { ConvertFrom-PovyTemplate $file.Content $file.Target } else { $file.Content }
            [pscustomobject]@{ Path = $file.Path; Text = $text; Private = $file.Private; Bom = [bool]$file.Bom }
        })
}

function Install-PovyWindowsFile($Rendered) {
    foreach ($file in $Rendered) {
        $staged = New-PovyStagedFile $file.Text -Bom:$file.Bom
        try {
            Install-PovyFile $staged $file.Path -Private:$file.Private
        } finally {
            Remove-Item -LiteralPath $staged -Force -ErrorAction Ignore
        }
    }
}
