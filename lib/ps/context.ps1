# Contexts, as in the bash engine: a Git identity, a profile, or both, below a
# directory. For a context with a profile, povy writes
# <dir>/.config/mise/conf.d/povy.toml, which includes the profile's team.toml: mise
# applies it to every directory below, to the tools that the shims start too, and
# the deepest context wins. The top-level profile is the default context, which
# mise's global conf.d applies everywhere.
#
# The functions written for one profile act on the current context, which
# Select-PovyContext sets: its clone, its .env files, its conf.d file.

$script:PovyContextHeader = '# Generated by povy apply for a context. Changes here are overwritten.'
$script:Ctx = $null
$script:PovyContextConf = $null
# What apply gathers from every profile: their commands, and their PowerShell files.
$script:PovyBins = @()
$script:PovyShellFiles = @()

# An absolute path without a trailing separator, from a dir of config.toml.
function Get-PovyContextPath([string]$Dir) {
    $path = $Dir
    if ($path.StartsWith('~/')) { $path = Join-Path $script:PovyHome $path.Substring(2) }
    return [System.IO.Path]::GetFullPath($path).TrimEnd('\', '/')
}

# How messages name the profile of a context.
function Get-PovyContextLabel([string]$Id) {
    if ($Id) { return "context $Id" }
    return 'the default profile'
}

# Makes a context current; an empty id is the default context.
function Select-PovyContext([string]$Id) {
    if (-not $Id) {
        $script:Ctx = [pscustomobject]@{
            Id = ''; Dir = ''; Profile = $script:Cfg.Profile; ProfileRef = $script:Cfg.ProfileRef; ProfilePath = $script:Cfg.ProfilePath
        }
        $script:PovyContextConf = $script:PovyMiseConf
        $script:PovyProfileDir = Join-Path $script:PovyStateDir 'profile'
        $script:PovyEnvFile = Join-Path $script:PovyConfigDir '.env'
        $script:PovyEnvFallback = $null
    } else {
        $context = @($script:Cfg.Contexts | Where-Object { $_.Id -ceq $Id })[0]
        $dir = Get-PovyContextPath $context.Dir
        $script:Ctx = [pscustomobject]@{
            Id = $Id; Dir = $dir; Profile = $context.Profile; ProfileRef = $context.ProfileRef; ProfilePath = $context.ProfilePath
        }
        $script:PovyContextConf = [System.IO.Path]::GetFullPath((Join-Path $dir '.config/mise/conf.d/povy.toml'))
        $script:PovyProfileDir = [System.IO.Path]::GetFullPath((Join-Path $script:PovyStateDir "contexts/$Id/profile"))
        $script:PovyEnvFile = Join-Path $script:PovyConfigDir "$Id.env"
        $script:PovyEnvFallback = Join-Path $script:PovyConfigDir '.env'
    }
    $script:PovyProfileRoot = $script:PovyProfileDir
    $script:Prof = New-PovyProfileState
}

# The ids of the default context, '', and of every context, in the order of
# config.toml.
function Get-PovyContextId {
    return @(@('') + @($script:Cfg.Contexts | ForEach-Object { $_.Id }))
}

# Writes the conf.d file of the current context and has mise trust it, as mise
# applies a project's config only once trusted. A profile without team.toml needs no
# file, and a file left from before goes.
function Set-PovyContextConf {
    if (-not $script:Prof.Team) {
        Remove-PovyContextConf $script:PovyContextConf
        return
    }
    Write-PovyMiseConf
    Invoke-PovyMise trust --quiet $script:PovyContextConf 2>$null | Out-Null
    if ($LASTEXITCODE -ne 0) { Stop-Povy "mise could not trust $script:PovyContextConf" }
}

# Removes a context's conf.d file, only when povy wrote it, and the directories that
# it leaves empty.
function Remove-PovyContextConf([string]$File) {
    if (-not (Test-Path -LiteralPath $File -PathType Leaf)) { return }
    $lines = [System.IO.File]::ReadAllLines($File)
    if ($lines.Count -eq 0 -or $lines[0] -cne $script:PovyContextHeader) { return }
    Remove-Item -LiteralPath $File -Force
    $dir = Split-Path -Parent $File
    foreach ($level in 1..3) {
        if (@(Get-ChildItem -LiteralPath $dir -Force -ErrorAction Ignore).Count -gt 0) { break }
        Remove-Item -LiteralPath $dir -Force -ErrorAction Ignore
        $dir = Split-Path -Parent $dir
    }
    $script:PovyWritten++
    Write-PovyInfo "removed $File"
}

# The contexts of the last apply, in the state file it leaves, as the bash engine
# writes it.
function Get-PovyAppliedFile {
    return Join-Path $script:PovyStateDir 'applied'
}

function Write-PovyAppliedState {
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# Written by povy apply.')
    $lines.Add("profile`t$($script:Cfg.Profile)")
    foreach ($context in $script:Cfg.Contexts) { $lines.Add("context`t$($context.Id)`t$($context.Dir)") }
    [System.IO.File]::WriteAllText((Get-PovyAppliedFile), ($lines -join "`n") + "`n", $script:PovyUtf8)
}

# Removes what povy wrote for the contexts of the last apply that are gone or that
# moved: their conf.d file, and the clone of those gone. Their .env stays, as it
# holds secrets.
function Remove-PovyStaleContext {
    $file = Get-PovyAppliedFile
    if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { return }
    foreach ($line in [System.IO.File]::ReadAllLines($file)) {
        $parts = $line.Split("`t")
        if ($parts.Count -lt 3 -or $parts[0] -cne 'context' -or -not $parts[1] -or -not $parts[2]) { continue }
        $now = @($script:Cfg.Contexts | Where-Object { $_.Id -ceq $parts[1] })
        if ($now.Count -gt 0 -and $now[0].Dir -ceq $parts[2]) { continue }
        Remove-PovyContextConf (Join-Path (Get-PovyContextPath $parts[2]) '.config/mise/conf.d/povy.toml')
        $clone = Join-Path $script:PovyStateDir "contexts/$($parts[1])"
        if ($now.Count -eq 0 -and (Test-Path -LiteralPath $clone)) { Remove-Item -LiteralPath $clone -Recurse -Force }
    }
}

# mise's os filter of a [bootstrap.files] entry, for this system: unix, macos, linux
# or windows, each with an optional /arch.
function Test-PovyOsMatch($Os) {
    if ($null -eq $Os -or ($Os -is [string] -and -not $Os)) { return $true }
    $here = if ($IsWindows) { 'windows' } elseif ($IsMacOS) { 'macos' } else { 'linux' }
    foreach ($item in @($Os)) {
        $name = ([string]$item).Split('/')[0]
        if ($name -ceq $here -or ($name -ceq 'unix' -and -not $IsWindows)) { return $true }
    }
    return $false
}

# The files that the current profile writes, each with the id of its block, or ''
# for a whole file: the [bootstrap.files] entries that mise applies on this system,
# and on Windows those that povy writes. mise bootstrap status does not tell a block
# from a file, so povy reads mise.toml.
function Get-PovyProfileTarget {
    $targets = [System.Collections.Generic.List[object]]::new()
    if (-not $script:Prof.Project) { return $targets.ToArray() }
    $file = $script:Prof.Project
    $data = Read-PovyToml $file
    $bootstrap = Get-PovyTomlTable $data 'bootstrap' $file '[bootstrap]'
    $files = Get-PovyTomlTable $bootstrap 'files' $file '[bootstrap.files]'
    foreach ($key in @($files.Keys)) {
        $entry = $files[$key]
        if ($entry -isnot [System.Collections.IDictionary] -or -not (Test-PovyOsMatch $entry['os'])) { continue }
        $path = if ($key.StartsWith('~/')) { Join-Path $script:PovyHome $key.Substring(2) } else { $key }
        $block = if ($entry.Contains('block')) { [string]$entry['id'] } else { '' }
        $targets.Add([pscustomobject]@{ Path = [System.IO.Path]::GetFullPath($path); Block = $block })
    }
    if ($IsWindows) {
        foreach ($windowsFile in $script:Prof.WindowsFiles) {
            $targets.Add([pscustomobject]@{ Path = [System.IO.Path]::GetFullPath($windowsFile.Path); Block = '' })
        }
    }
    return $targets.ToArray()
}

# One line per file that two profiles write, from entries with Owner, Path and Block.
# Two blocks of different ids in one file do not conflict: mise keeps both.
function Get-PovyConflict($Targets) {
    $comparer = if ($IsWindows) { [StringComparer]::OrdinalIgnoreCase } else { [StringComparer]::Ordinal }
    $seen = [System.Collections.Generic.Dictionary[string, System.Collections.Generic.List[object]]]::new($comparer)
    $conflicts = [System.Collections.Generic.List[string]]::new()
    foreach ($target in $Targets) {
        if (-not $seen.ContainsKey($target.Path)) { $seen[$target.Path] = [System.Collections.Generic.List[object]]::new() }
        foreach ($other in $seen[$target.Path]) {
            if ($other.Owner -cne $target.Owner -and (-not $other.Block -or -not $target.Block -or $other.Block -ceq $target.Block)) {
                $line = "$(Format-PovyPath $target.Path): written by $(Get-PovyContextLabel $other.Owner) and by $(Get-PovyContextLabel $target.Owner)"
                if (-not $conflicts.Contains($line)) { $conflicts.Add($line) }
            }
        }
        $seen[$target.Path].Add($target)
    }
    return $conflicts.ToArray()
}

# One line per command that two profiles' bin directories both have, from entries
# with Owner and Dir. The first, in the order of config.toml, comes first on PATH.
function Get-PovyBinCollision($Bins) {
    $comparer = if ($IsWindows) { [StringComparer]::OrdinalIgnoreCase } else { [StringComparer]::Ordinal }
    $first = [System.Collections.Generic.Dictionary[string, string]]::new($comparer)
    $collisions = [System.Collections.Generic.List[string]]::new()
    foreach ($bin in $Bins) {
        foreach ($file in @(Get-ChildItem -LiteralPath $bin.Dir -File -ErrorAction Ignore)) {
            if ($IsWindows) {
                if ($file.Extension -notin '.ps1', '.cmd', '.bat', '.exe') { continue }
                $name = $file.BaseName
            } else {
                if (-not ($file.UnixFileMode -band [System.IO.UnixFileMode]::UserExecute)) { continue }
                $name = $file.Name
            }
            if (-not $first.ContainsKey($name)) {
                $first[$name] = $bin.Owner
            } elseif ($first[$name] -cne $bin.Owner) {
                $line = "${name}: in $(Get-PovyContextLabel $first[$name]) and in $(Get-PovyContextLabel $bin.Owner); the first wins"
                if (-not $collisions.Contains($line)) { $collisions.Add($line) }
            }
        }
    }
    return $collisions.ToArray()
}

# The contexts and the [[identities]] entries whose directory holds the given one,
# the deepest first, each with the Label that status shows. They come in the reverse
# of the order Git applies them, so that of an identity and a context of the same
# directory, the context, which Git applies last, comes first.
function Get-PovyContextMatch([string]$Dir) {
    $entries = @(foreach ($identity in $script:Cfg.Identities) {
            [pscustomobject]@{ Label = '(identity)'; Dir = $identity.Dir; Email = $identity.Email; Profile = ''; ProfileRef = '' }
        }) + @(foreach ($context in $script:Cfg.Contexts) {
            [pscustomobject]@{
                Label = $context.Id; Dir = $context.Dir; Email = $context.Email; Profile = $context.Profile; ProfileRef = $context.ProfileRef
            }
        })
    $order = 0
    $matched = foreach ($entry in $entries) {
        $order++
        $path = Get-PovyContextPath $entry.Dir
        $same = if ($IsWindows) { $Dir -ieq $path } else { $Dir -ceq $path }
        if ($same -or ((Test-Path -LiteralPath $path) -and (Test-PovyWithin $Dir $path))) {
            [pscustomobject]@{ Entry = $entry; Length = $path.Length; Order = $order }
        }
    }
    $sorted = $matched | Sort-Object -Property @{ Expression = 'Length'; Descending = $true }, @{ Expression = 'Order'; Descending = $true }
    return @($sorted | ForEach-Object { $_.Entry })
}
