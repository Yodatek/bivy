# Git identity, as in the bash engine: povy generates a Git config from config.toml
# and includes it from a marked block at the top of the global config. Whatever comes
# after the block keeps precedence, so povy reports a [user] there instead of removing
# it. Directories match with gitdir/i:, since Windows paths ignore case.

$script:PovyGitHeader = '# Generated by povy apply from config.toml. Changes here are overwritten.'

# Git reads ~/.gitconfig, or only the XDG file when ~/.gitconfig does not exist.
function Get-PovyGitGlobalFile {
    $default = Join-Path $script:PovyHome '.gitconfig'
    $configBase = if ($env:XDG_CONFIG_HOME) { $env:XDG_CONFIG_HOME } else { Join-Path $script:PovyHome '.config' }
    $xdg = Join-Path $configBase 'git/config'
    if (-not (Get-Item -LiteralPath $default -Force -ErrorAction Ignore) -and (Test-Path -LiteralPath $xdg)) { return $xdg }
    return $default
}

# A path as a Git config value: ~/ and forward slashes when it lies in the home
# directory, so that the block stays valid in a dotfiles repository.
function ConvertTo-PovyGitPath([string]$Path) {
    $homeDir = $script:PovyHome
    if ($Path.StartsWith($homeDir + [System.IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        $rest = $Path.Substring($homeDir.Length + 1).Replace('\', '/')
        if ($rest -cmatch '^[A-Za-z0-9._/-]+$') { return "~/$rest" }
    }
    return '"' + $Path.Replace('\', '/').Replace('"', '\"') + '"'
}

function Get-PovyGitBlock {
    return @(
        (Get-PovyBlockMarker ''),
        '# Managed by povy. Edits inside this block are overwritten.',
        '[include]',
        "`tpath = $(ConvertTo-PovyGitPath (Join-Path $script:PovyGitDir 'config'))",
        (Get-PovyBlockMarker '' -End)
    ) -join "`n"
}

# git config -f does the quoting, so names and paths need no escaping here.
function Write-PovyGitIdentity([string]$File, [string]$Name, [string]$Email) {
    [System.IO.File]::WriteAllText($File, "$script:PovyGitHeader`n", $script:PovyUtf8)
    foreach ($pair in @(@('user.name', $Name), @('user.email', $Email))) {
        if ((Invoke-PovyGit @('config', '-f', $File, $pair[0], $pair[1])).Code -ne 0) { return $false }
    }
    return $true
}

# Renders every generated file into Dir. Include paths are relative, and Git resolves
# them from the including file.
function Write-PovyGitConfig([string]$Dir) {
    if (-not (Write-PovyGitIdentity (Join-Path $Dir 'config') $script:Cfg.Name $script:Cfg.Email)) { return $false }
    $index = 0
    foreach ($identity in $script:Cfg.Identities) {
        $index++
        if (-not (Write-PovyGitIdentity (Join-Path $Dir "identity-$index") $identity.Name $identity.Email)) { return $false }
        $key = "includeIf.gitdir/i:$($identity.Dir).path"
        if ((Invoke-PovyGit @('config', '-f', (Join-Path $Dir 'config'), $key, "identity-$index")).Code -ne 0) { return $false }
    }
    return $true
}

# The files that set user.name or user.email after the povy include of the global
# config, and so override the identities povy sets.
function Get-PovyGitOverridingFile {
    $global = Get-PovyGitGlobalFile
    if (-not (Test-Path -LiteralPath $global -PathType Leaf)) { return @() }
    $result = Invoke-PovyGit @('config', '-f', $global, '--includes', '--show-origin', '--get-regexp', '^user\.(name|email)$')
    if ($result.Code -ne 0 -or -not $result.Output) { return @() }
    $ours = ($script:PovyGitDir.Replace('\', '/')).TrimEnd('/') + '/'
    $files = foreach ($line in $result.Output -split "`n") {
        $origin = ($line -split "`t", 2)[0]
        if ($origin.StartsWith('file:')) { $origin = $origin.Substring(5) }
        if (-not $origin.Replace('\', '/').StartsWith($ours, [StringComparison]::OrdinalIgnoreCase)) { $origin }
    }
    return @($files | Select-Object -Unique)
}

function Update-PovyGit {
    if (-not (Get-Command git -CommandType Application -ErrorAction Ignore)) {
        Write-PovyWarning 'git is not installed; the Git identity is not set'
        return
    }
    $stage = Join-Path $script:PovyStateDir ('git.' + [System.Guid]::NewGuid().ToString('N').Substring(0, 8))
    New-Item -ItemType Directory -Force -Path $stage | Out-Null
    try {
        if (-not (Write-PovyGitConfig $stage)) { Stop-Povy 'could not generate the Git configuration' }
        foreach ($file in Get-ChildItem -LiteralPath $stage -File) {
            Install-PovyFile $file.FullName (Join-Path $script:PovyGitDir $file.Name)
        }
        foreach ($file in @(Get-ChildItem -LiteralPath $script:PovyGitDir -Filter 'identity-*' -File -ErrorAction Ignore)) {
            if (Test-Path -LiteralPath (Join-Path $stage $file.Name)) { continue }
            Remove-Item -LiteralPath $file.FullName -Force
            $script:PovyWritten++
            Write-PovyInfo "removed $($file.FullName)"
        }
    } finally {
        Remove-Item -LiteralPath $stage -Recurse -Force -ErrorAction Ignore
    }

    Set-PovyBlock -File (Get-PovyGitGlobalFile) -Block (Get-PovyGitBlock) -Position top

    $overriding = @(Get-PovyGitOverridingFile)
    if ($overriding.Count -gt 0) {
        Write-PovyWarning 'these files set user.name or user.email after the povy include, so they override it:'
        Write-PovyInfo ($overriding -join "`n")
        Write-PovyInfo 'Remove those settings, or move them to config.toml.'
    }
}
