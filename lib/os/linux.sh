# systemd reads environment.d at login and passes it to the graphical session.
# Without systemd the file is simply ignored.
os_gui_file() { printf '%s\n' "${XDG_CONFIG_HOME:-$HOME/.config}/environment.d/50-bivy.conf"; }

# environment.d expands $VAR and parses quotes, so only plain paths are written,
# with ${HOME} when possible, like in the shell startup files.
env_d_path() {
  local path=$1 prefix=""
  case "$path" in
    "$HOME"/*)
      # shellcheck disable=SC2016
      prefix='${HOME}/'
      path=${path#"$HOME"/}
      ;;
    /*) ;;
    *) return 1 ;;
  esac
  [[ "$path" =~ ^[A-Za-z0-9._/@+-]+$ ]] || return 1
  printf '%s%s' "$prefix" "$path"
}

os_gui_render() {
  local out=$1 shims bin
  shims=$(env_d_path "$BIVY_SHIMS_DIR") || return 1
  bin=$(env_d_path "$BIVY_LOCAL_BIN") || return 1
  {
    echo '# Generated by bivy apply. Changes here are overwritten.'
    # shellcheck disable=SC2016
    printf 'PATH=%s:%s:${PATH}\n' "$shims" "$bin"
  } >"$out"
}

os_gui_activate() {
  [ "$1" -eq 0 ] || info "graphical apps get the shims from the next login"
}

# 2: the running session cannot be checked, environment.d applies at login.
os_gui_session_state() { return 2; }

# Prints the one-minute load average and the number of cores.
os_cpu_load() {
  local load rest
  read -r load rest </proc/loadavg || return 1
  printf '%s %s\n' "$load" "$(getconf _NPROCESSORS_ONLN)"
}

# Prints the memory in use and the total, in bytes.
os_memory() {
  LC_ALL=C awk '/^MemTotal:/ { t = $2 } /^MemAvailable:/ { a = $2 }
    END { printf "%.0f %.0f\n", (t - a) * 1024, t * 1024 }' /proc/meminfo
}
