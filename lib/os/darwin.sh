# shellcheck shell=bash
# macOS adapter: BSD userland.

# Replaced by a recording stub in the test suite, so that tests never change the
# environment of the real graphical session.
POVY_LAUNCHCTL=${POVY_LAUNCHCTL:-launchctl}
POVY_GUI_LABEL="povy.env"
POVY_GUI_DEFAULT_PATH="/usr/bin:/bin:/usr/sbin:/sbin"

os_file_mode() { stat -f '%Lp' "$1"; }

os_bash_login_default() { echo .bash_profile; }

os_preflight() { :; }

os_doctor() { :; }

# Apps started from the Dock or the Finder get their environment from launchd, not
# from a shell. A LaunchAgent runs `launchctl setenv PATH` at each login.
os_gui_file() { printf '%s\n' "$HOME/Library/LaunchAgents/$POVY_GUI_LABEL.plist"; }

xml_escape() {
  printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
}

# The agent sources env.sh, so the PATH it sets follows any later change there.
# The path is written with $HOME when possible, like in the shell startup files.
os_gui_render() {
  local out=$1 script
  has_control_chars "$POVY_ENV_SH" && return 1
  # shellcheck disable=SC2016
  script=". $(shell_path_literal "$POVY_ENV_SH")"' && exec "$1" setenv PATH "$PATH"'
  cat >"$out" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by povy apply. Changes here are overwritten. -->
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>$POVY_GUI_LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/sh</string>
    <string>-c</string>
    <string>$(xml_escape "$script")</string>
    <string>povy-gui-env</string>
    <string>/bin/launchctl</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
</dict>
</plist>
EOF
}

# The agent only runs at the next login, so apply sets the PATH now as well. It
# starts from the current value, which keeps what the user or another tool added.
os_gui_activate() {
  local current wanted
  current=$("$POVY_LAUNCHCTL" getenv PATH 2>/dev/null) || current=""
  wanted=$(gui_path_from "${current:-$POVY_GUI_DEFAULT_PATH}") || die "could not compute the PATH for graphical apps"
  [ "$current" != "$wanted" ] || return 0
  if "$POVY_LAUNCHCTL" setenv PATH "$wanted" 2>/dev/null; then
    info "set PATH for graphical apps started from now on"
  else
    warn "could not set PATH for graphical apps now; it will be set at the next login"
  fi
}

# 0 when graphical apps started now see the shims, 1 when they do not.
os_gui_session_state() {
  local current
  current=$("$POVY_LAUNCHCTL" getenv PATH 2>/dev/null) || current=""
  case ":$current:" in
    *":$POVY_SHIMS_DIR:"*) return 0 ;;
  esac
  return 1
}

# Prints the one-minute load average and the number of cores. Full paths: /usr/sbin
# is missing from the minimal PATH that some apps give their shells.
os_cpu_load() {
  local load
  load=$(/usr/sbin/sysctl -n vm.loadavg) || return 1
  load=${load#\{ }
  printf '%s %s\n' "${load%% *}" "$(/usr/sbin/sysctl -n hw.ncpu)"
}

# Prints the memory in use and the total, in bytes. In use counts as Activity
# Monitor does: app memory, wired and compressed.
os_memory() {
  local total
  total=$(/usr/sbin/sysctl -n hw.memsize) || return 1
  /usr/bin/vm_stat | LC_ALL=C awk -v total="$total" '
    /page size of/ { size = $(NF - 1) }
    /^Anonymous pages:/ { anon = $3 }
    /^Pages purgeable:/ { purgeable = $3 }
    /^Pages active:/ { active = $3 }
    /^Pages wired down:/ { wired = $4 }
    /^Pages occupied by compressor:/ { compressed = $5 }
    END {
      app = (anon != "") ? anon - purgeable : active
      printf "%.0f %.0f\n", (app + wired + compressed) * size, total
    }'
}
