# shellcheck shell=bash
# Contexts: a Git identity, a profile, variables, or several, below a directory.
# For a context with a profile or variables, povy writes
# <dir>/.config/mise/conf.d/povy.toml, which includes the profile's team.toml and
# sets the variables: mise applies it to every directory below, to the tools that
# IDEs and agents start through the shims too, and the deepest context wins. The
# top-level profile is the default context, which mise's global conf.d applies
# everywhere.
#
# The functions written for one profile act on the current context, which
# context_select sets: its clone, its .env files, its conf.d file.

CONTEXT_ID=""
CONTEXT_DIR=""
CONTEXT_CONF=""
# The profiles' bin directories, one per line, the first in config.toml first.
POVY_BINS=""

POVY_CONTEXT_HEADER='# Generated by povy apply for a context. Changes here are overwritten.'

# An absolute path without its trailing slash, from a dir of config.toml.
context_path() {
  local dir=${1%/}
  # A literal ~/ of config.toml.
  # shellcheck disable=SC2088
  case "$dir" in
    '~/'*) dir="$HOME/${dir#\~/}" ;;
  esac
  printf '%s' "$dir"
}

# The ids of the contexts, in the order of config.toml.
context_ids() {
  printf '%s\n' "$CFG_CONTEXTS" | awk -F'\t' 'NF { print $1 }'
}

# One field of a context: 2 dir, 3 name, 4 email, 5 profile, 6 ref, 7 path.
context_field() {
  printf '%s\n' "$CFG_CONTEXTS" | awk -F'\t' -v id="$1" -v n="$2" '$1 == id { print $n; exit }'
}

# The variables of a context, "name<TAB>value" lines, in the order of config.toml.
context_env() {
  printf '%s\n' "$CFG_CONTEXT_ENV" | awk -F'\t' -v id="$1" '$1 == id { print $2 "\t" $3 }'
}

# How messages name the profile of a context.
context_label() {
  if [ -n "${1:-}" ]; then
    printf 'context %s' "$1"
  else
    printf 'the default profile'
  fi
}

# Makes a context current; an empty id is the default context.
context_select() {
  local id=$1
  CONTEXT_ID=$id
  if [ -z "$id" ]; then
    CONTEXT_DIR=""
    CONTEXT_CONF=$POVY_MISE_CONF
    POVY_PROFILE_DIR="$POVY_STATE_DIR/profile"
    POVY_ENV_FILE="$POVY_CONFIG_DIR/.env"
    POVY_ENV_FALLBACK=""
    CFG_PROFILE=$CFG_DEFAULT_PROFILE
    CFG_PROFILE_REF=$CFG_DEFAULT_PROFILE_REF
    CFG_PROFILE_PATH=$CFG_DEFAULT_PROFILE_PATH
  else
    CONTEXT_DIR=$(context_path "$(context_field "$id" 2)")
    CONTEXT_CONF="$CONTEXT_DIR/.config/mise/conf.d/povy.toml"
    POVY_PROFILE_DIR="$POVY_STATE_DIR/contexts/$id/profile"
    POVY_ENV_FILE="$POVY_CONFIG_DIR/$id.env"
    POVY_ENV_FALLBACK="$POVY_CONFIG_DIR/.env"
    CFG_PROFILE=$(context_field "$id" 5)
    CFG_PROFILE_REF=$(context_field "$id" 6)
    CFG_PROFILE_PATH=$(context_field "$id" 7)
  fi
  POVY_PROFILE_ROOT=$POVY_PROFILE_DIR
  PROFILE_TEAM=""
  PROFILE_PROJECT=""
  PROFILE_BIN=""
}

# Writes the conf.d file of the current context and has mise trust it, as mise
# applies a project's config only once trusted. A context with neither a team.toml
# nor variables needs no file, and a file left from before goes.
context_conf_apply() {
  if [ -z "$PROFILE_TEAM" ] && [ -z "$(context_env "$CONTEXT_ID")" ]; then
    context_conf_remove "$CONTEXT_CONF"
    return 0
  fi
  team_conf_write
  mise_run trust --quiet "$CONTEXT_CONF" >/dev/null ||
    die "mise could not trust $CONTEXT_CONF; see above"
}

# Removes a context's conf.d file, only when povy wrote it, and the directories
# that it leaves empty.
context_conf_remove() {
  local file=$1
  [ -f "$file" ] && [ "$(head -n 1 "$file")" = "$POVY_CONTEXT_HEADER" ] || return 0
  rm -f "$file" || die "cannot remove $file"
  rmdir "${file%/*}" "${file%/*/*}" "${file%/*/*/*}" 2>/dev/null || true
  POVY_WRITTEN=$((POVY_WRITTEN + 1))
  info "removed $file"
}

# Removes what povy wrote for the contexts of the last apply that are gone or that
# moved: their conf.d file, and the clone of those gone. Their .env stays, as it
# holds secrets.
context_cleanup() {
  local kind id dir now
  [ -f "$POVY_APPLIED" ] || return 0
  while IFS=$'\t' read -r kind id dir; do
    [ "$kind" = context ] && [ -n "$id" ] && [ -n "$dir" ] || continue
    now=$(context_field "$id" 2)
    [ "$now" != "$dir" ] || continue
    context_conf_remove "$(context_path "$dir")/.config/mise/conf.d/povy.toml"
    if [ -z "$now" ] && [ -d "$POVY_STATE_DIR/contexts/$id" ]; then
      rm -rf "${POVY_STATE_DIR:?}/contexts/$id" || die "cannot remove the clone of context $id"
    fi
  done <"$POVY_APPLIED"
}

# mise's os filter of a [bootstrap.files] entry: unix, macos, linux or windows,
# each with an optional /arch.
context_os_matches() {
  local list=$1 os item
  [ -n "$list" ] || return 0
  case "${POVY_OS:-}" in
    darwin) os=macos ;;
    *) os=linux ;;
  esac
  for item in ${list//,/ }; do
    item=${item%%/*}
    if [ "$item" = unix ] || [ "$item" = "$os" ]; then
      return 0
    fi
  done
  return 1
}

# Prints "target<TAB>block id" for each [bootstrap.files] entry of the current
# profile that applies on this system; the id is empty for a whole file. mise
# bootstrap status does not tell a block from a file, so povy reads mise.toml.
profile_file_targets() {
  local entries target id block os
  [ -n "$PROFILE_PROJECT" ] || return 0
  entries=$("$POVY_YQ" -p toml -o tsv '(.bootstrap.files // {}) | to_entries | .[] |
    [.key, (.value.id // ""), (.value | has("block") | tostring),
     ((.value.os // "") | [.] | flatten | join(","))]' "$PROFILE_PROJECT") ||
    die "cannot read [bootstrap.files] in $PROFILE_PROJECT"
  while IFS=$'\t' read -r target id block os; do
    [ -n "$target" ] || continue
    context_os_matches "$os" || continue
    # A literal ~/ of mise.toml.
    # shellcheck disable=SC2088
    case "$target" in
      '~/'*) target="$HOME/${target#\~/}" ;;
    esac
    [ "$block" = true ] || id=""
    printf '%s\t%s\n' "$target" "$id"
  done <<<"$entries"
}

# Prints "target<TAB>owner<TAB>other owner" for each file that two profiles write,
# from lines "owner<TAB>target<TAB>block id". Two blocks of different ids in one
# file do not conflict: mise keeps both.
context_conflicts() {
  printf '%s\n' "$1" | awk -F'\t' '
    NF >= 2 && $2 != "" {
      for (i = 1; i <= n[$2]; i++)
        if (owner[$2, i] != $1 && (id[$2, i] == "" || $3 == "" || id[$2, i] == $3))
          print $2 "\t" owner[$2, i] "\t" $1
      n[$2]++
      owner[$2, n[$2]] = $1
      id[$2, n[$2]] = $3
    }' | awk '!seen[$0]++'
}

# One line per conflict, for apply and doctor.
context_conflicts_text() {
  local target a b
  while IFS=$'\t' read -r target a b; do
    [ -n "$target" ] || continue
    printf '%s: written by %s and by %s\n' "$(tilde_path "$target")" "$(context_label "$a")" "$(context_label "$b")"
  done <<<"$1"
}

# Prints "command<TAB>owner<TAB>other owner" for each command that two profiles'
# bin directories both have, from lines "owner<TAB>dir". The first owner, in the
# order of config.toml, comes first on PATH and wins.
context_bin_collisions() {
  local owner dir file
  while IFS=$'\t' read -r owner dir; do
    [ -n "$dir" ] && [ -d "$dir" ] || continue
    for file in "$dir"/*; do
      [ -f "$file" ] && [ -x "$file" ] || continue
      printf '%s\t%s\n' "${file##*/}" "$owner"
    done
  done <<<"$1" | awk -F'\t' '
    { if ($1 in first) { if (first[$1] != $2) print $1 "\t" first[$1] "\t" $2 } else first[$1] = $2 }'
}

context_bin_collisions_text() {
  local name a b
  while IFS=$'\t' read -r name a b; do
    [ -n "$name" ] || continue
    printf '%s: in %s and in %s; the first wins\n' "$name" "$(context_label "$a")" "$(context_label "$b")"
  done <<<"$1"
}

# The contexts and the [[identities]] entries whose directory holds the given one,
# the deepest first: "context<TAB>id", or "identity<TAB>dir<TAB>email". They come in
# the reverse of the order Git applies them, so that of an identity and a context of
# the same directory, the context, which Git applies last, comes first.
context_matching() {
  local target=$1 n=0 id dir email path
  {
    while IFS=$'\t' read -r dir _ email; do
      [ -n "$dir" ] || continue
      n=$((n + 1))
      path=$(context_path "$dir")
      if [ "$target" = "$path" ] || path_within "$target" "$path"; then
        printf '%s\t%s\tidentity\t%s\t%s\n' "${#path}" "$n" "$dir" "$email"
      fi
    done <<<"$CFG_IDENTITIES"
    while IFS= read -r id; do
      [ -n "$id" ] || continue
      n=$((n + 1))
      path=$(context_path "$(context_field "$id" 2)")
      if [ "$target" = "$path" ] || path_within "$target" "$path"; then
        printf '%s\t%s\tcontext\t%s\n' "${#path}" "$n" "$id"
      fi
    done <<<"$(context_ids)"
  } | sort -t$'\t' -k1,1nr -k2,2nr | cut -f3-
}
